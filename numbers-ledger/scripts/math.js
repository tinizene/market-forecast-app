/** Numerical Recipes' Chebyshev erfc. Accurate to about 1.2e-7, which is ample. */
function erfc(x) {
  const z = Math.abs(x);
  const t = 2 / (2 + z);
  const ty = 4 * t - 2;
  const coefficients = [
    -1.3026537197817094, 6.4196979235649026e-1, 1.9476473204185836e-2,
    -9.561514786808631e-3, -9.46595344482036e-4, 3.66839497852761e-4,
    4.2523324806907e-5, -2.0278578112534e-5, -1.624290004647e-6,
    1.303655835580e-6, 1.5626441722e-8, -8.5238095915e-8,
    6.529054439e-9, 5.059343495e-9, -9.91364156e-10,
    -2.27365122e-10, 9.6467911e-11, 2.394038e-12,
    -6.886027e-12, 8.94487e-13, 3.13092e-13,
    -1.12708e-13, 3.81e-16, 7.106e-15
  ];
  let d = 0;
  let dd = 0;
  for (let j = coefficients.length - 1; j > 0; j--) {
    const tmp = d;
    d = ty * d - dd + coefficients[j];
    dd = tmp;
  }
  const answer = t * Math.exp(-z * z + 0.5 * (coefficients[0] + ty * d) - dd);
  return x >= 0 ? answer : 2 - answer;
}

/**
 * Does the draw derivation reach all 1,000 outcomes evenly?
 *
 * Seeds are derived deterministically - sha256 of a counter - so this section
 * reproduces exactly and a reviewer can re-run it and get the same numbers. The
 * claim is correspondingly narrow, and stating it narrowly is the point:
 *
 *   This tests the MAPPING from a seed to a result: the HMAC, the rejection
 *   sampling, and the scaling to 000-999. It says nothing about the entropy of
 *   a real seed, which comes from the platform CSPRNG and is not this test's
 *   business.
 *
 * Chi-square against a uniform expectation over 1,000 buckets, with the tail
 * probability from the Wilson-Hilferty transform, which is the standard normal
 * approximation for a chi-square with many degrees of freedom.
 */
function uniformity({ samples = 1_000_000, drawKey = 'uniformity' } = {}) {
  const buckets = new Uint32Array(OUTCOMES);
  for (let i = 0; i < samples; i++) {
    const seed = crypto.createHash('sha256').update(`math-sheet|${i}`, 'utf8').digest('hex');
    buckets[Number(draws.resultFromSeed(drawKey, seed))] += 1;
  }

  const expected = samples / OUTCOMES;
  let chiSquare = 0;
  for (const observed of buckets) chiSquare += ((observed - expected) ** 2) / expected;

  const df = OUTCOMES - 1;
  const ratio = (chiSquare / df) ** (1 / 3);
  const mean = 1 - 2 / (9 * df);
  const sd = Math.sqrt(2 / (9 * df));
  const z = (ratio - mean) / sd;
  // Two-sided: a fit that is too good is as suspicious as one that is too bad.
  const p = erfc(Math.abs(z) / Math.SQRT2);

  return {
    samples, drawKey, df, chiSquare, z, p,
    expectedPerOutcome: expected,
    minBucket: Math.min(...buckets),
    maxBucket: Math.max(...buckets),
    emptyBuckets: [...buckets].filter((count) => count === 0).length
  };
}

function compute({ samples = 1_000_000, maxStake = 10_000 } = {}) {
  const rows = board({ maxStake });
  return {
    currency: CONFIG.currency,
    outcomes: OUTCOMES,
    runnerCutPct: game.RUNNER_CUT_PCT,
    week: WEEK,
    rows,
    mixes: mixes(rows),
    uniformity: uniformity({ samples }),
    maxStake
  };
}

module.exports = {
  compute, board, mixes, uniformity, winCountsFor, selectionsFor, roundingFor, erfc,
  OUTCOMES, TYPE_ORDER, ALL_RESULTS, WEEK
};
